/**
 * 字体就位：把 craft-fonts 里选中的字体拷进 dist/fonts/ 并生成 manifest.txt。
 * ------------------------------------------------------------------
 * 上游 PhotoCraft 的网页版把字体作为**站点根下的独立文件**分发：启动时 fetch
 * `fonts/manifest.txt`（craft-fonts 的清单格式：family | style | file | scripts |
 * licence | licence file | sha256 | source），再按需 fetch 具体字体文件。
 * 本插件照抄同一约定——所以只需要把字体放到 dist/fonts/ 下、路径与 manifest 一致。
 *
 * 与模板的 fetch-cjk-fonts.mjs 分工：那个负责把 craft-fonts 浅拉到 ../cjk-fonts
 * （兄弟目录，不入库）；本脚本负责「选哪些、拷到哪、写 manifest」。
 * 字体缺失不致命：界面里的中日韩/阿拉伯/泰文会显示方框（启动不受影响）。
 *
 * 用法：node scripts/prepare-fonts.mjs
 *   OT_FONTS_SRC=<本地 craft-fonts 检出>   离线环境直接取文件（跳过网络）
 */
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pinPath = path.join(repoRoot, 'cjk-fonts.pin');
if (!fs.existsSync(pinPath)) {
  console.log('没有 cjk-fonts.pin：跳过字体就位。');
  process.exit(0);
}
const pin = JSON.parse(fs.readFileSync(pinPath, 'utf8'));
if (!/^[0-9a-f]{40}$/.test(pin.commit ?? '')) {
  console.error('cjk-fonts.pin 的 commit 必须是 40 位完整 SHA');
  process.exit(1);
}

// 字体来源：优先 OT_FONTS_SRC（本地检出），否则 ../cjk-fonts（fetch-cjk-fonts.mjs 拉的兄弟目录）。
const localSrc = process.env.OT_FONTS_SRC;
const sibling = path.resolve(repoRoot, '..', 'cjk-fonts');
const sourceRoot = localSrc && fs.existsSync(localSrc) ? localSrc : (fs.existsSync(sibling) ? sibling : null);
if (!sourceRoot) {
  console.warn('! 找不到字体来源（../cjk-fonts 或 OT_FONTS_SRC）：本次构建不带 CJK 字体，中文会显示方框。');
  process.exit(0);
}

const dist = path.join(repoRoot, 'dist');
if (!fs.existsSync(dist)) {
  console.error('dist/ 不存在：请先跑 node scripts/build-web.mjs。');
  process.exit(1);
}
const fontsDir = path.join(dist, 'fonts');
fs.mkdirSync(fontsDir, { recursive: true });

const sha256 = (file) => createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const lines = [
  '# Font manifest for the Crafting Apps. Generated by scripts/prepare-fonts.mjs',
  '#   family | style | file (relative to the site root) | scripts | licence | licence file | sha256 | source',
];
let failed = 0;
for (const font of pin.fonts ?? []) {
  const from = path.join(sourceRoot, font.file);
  const to = path.join(dist, font.file);
  if (!fs.existsSync(from)) {
    console.warn(`  ! ${font.family} ${font.style}：字体来源里没有 ${font.file}`);
    failed += 1;
    continue;
  }
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.copyFileSync(from, to);
  const digest = sha256(to);
  if (font.sha256 && digest !== font.sha256) {
    console.warn(`  ! ${font.family} ${font.style}：sha256 不符（期望 ${font.sha256.slice(0, 12)}，实际 ${digest.slice(0, 12)}）`);
    failed += 1;
  }
  const licenceTo = path.join(dist, font.licence);
  fs.mkdirSync(path.dirname(licenceTo), { recursive: true });
  const licenceFrom = path.join(sourceRoot, font.licence);
  if (fs.existsSync(licenceFrom)) fs.copyFileSync(licenceFrom, licenceTo);
  lines.push([font.family, font.style, font.file, font.scripts, 'OFL-1.1', font.licence, digest, `https://github.com/${pin.upstream}`].join(' | '));
  console.log(`✓ ${font.family} ${font.style} → ${path.relative(repoRoot, to)}（${(fs.statSync(to).size / 1048576).toFixed(1)} MB）`);
}

fs.writeFileSync(path.join(fontsDir, 'manifest.txt'), `${lines.join('\n')}\n`);
if (failed) {
  console.warn(`! ${failed} 个字体没就位：界面里对应文字会显示方框（不影响启动）。`);
}
console.log(`字体就位：dist/fonts/（${(pin.fonts ?? []).length - failed}/${(pin.fonts ?? []).length}）`);